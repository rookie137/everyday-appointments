export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("ea_lang") || "ml");
  useEffect(() => { localStorage.setItem("ea_lang", lang); }, [lang]);
  const t = (k) => STRINGS[lang]?.[k] ?? STRINGS.en[k] ?? k;
  const toggle = () => setLang((l) => (l === "ml" ? "en" : "ml"));
  return <LangCtx.Provider value={{ lang, setLang, toggle, t }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);

// Malayalam WhatsApp message template for booking receipt
export function buildWhatsappMessage(t, { clinicName, doctorName, place, date, time, token, patientName, patientPlace }) {
  // Language-neutral core + Malayalam label lines
  const lines = [
    `നമസ്കാരം ${clinicName}`,
    `പേര്: ${patientName}`,
    patientPlace ? `സ്ഥലം: ${patientPlace}` : "",
    doctorName ? `${t("doctor")}: ${doctorName}` : "",
    place ? `Clinic: ${clinicName}, ${place}` : "",
    `${t("date")}: ${date}`,
    `${t("time")}: ${time}`,
    `${t("token")} #${token}`,
    "",
    "അപ്പോയിന്റ്‌മെന്റ് സ്ഥിരീകരണം. നന്ദി.",
  ].filter(Boolean);
  return lines.join("\n");
}

// Emergency cancellation WA message
export function buildCancelMessage({ clinicName, date, patientName, time, token }) {
  return [
    `നമസ്കാരം ${patientName},`,
    `${clinicName} ന്റെ ${date} തീയതിയിലെ അപ്പോയിന്റ്‌മെന്റ് (സമയം ${time}, ടോക്കൺ #${token}) റദ്ദാക്കിയിരിക്കുന്നു.`,
    "അസൗകര്യത്തിന് ക്ഷമിക്കണം. പുതിയ സമയം വേണമെങ്കിൽ ബുക്ക് ചെയ്യുക.",
  ].join("\n");
}

// Morning reminder WA message for clinic staff
export function buildMorningReminderMessage({ clinicName, date, count, firstTime, appUrl }) {
  if (!count || count === 0) {
    return [
      `🌅 സുപ്രഭാതം ${clinicName}!`,
      `${date} — ഇന്ന് ബുക്കിംഗുകൾ ഇല്ല.`,
      appUrl ? `App: ${appUrl}` : "",
    ].filter(Boolean).join("\n");
  }
  return [
    `🌅 സുപ്രഭാതം ${clinicName}!`,
    `${date} — ഇന്ന് ${count} രോഗികൾ ബുക്ക് ചെയ്തിട്ടുണ്ട്.`,
    firstTime ? `ആദ്യത്തെ ടോക്കൺ: ${firstTime}` : "",
    "ആപ്പ് തുറന്ന് ടോക്കൺ ചെക്ക് ചെയ്യുക.",
    appUrl ? `Open: ${appUrl}` : "",
  ].filter(Boolean).join("\n");
}
